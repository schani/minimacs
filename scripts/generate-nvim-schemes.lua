-- Regenerates src/theme/nvim_schemes.rs: a snapshot of the highlight groups
-- minimacs uses, for every Neovim colorscheme an Omarchy stock theme selects.
--
-- Needs an Omarchy LazyVim install (the colorscheme plugins live there). Run:
--
--   MINIMACS_OUT=src/theme/nvim_schemes.rs \
--     nvim --headless "+luafile scripts/generate-nvim-schemes.lua" +qa
--
-- `aether` is not snapshotted: it is computed from a theme's colors.toml at
-- runtime (src/theme/omarchy.rs). One aether theme is dumped as a test fixture
-- instead, so that port stays faithful.

local schemes = {
  "ashen", "catppuccin-latte", "catppuccin-mocha", "everforest", "flexoki-light",
  "gruvbox", "hackerman", "kanagawa", "lumon", "matteblack", "nordfox", "retro-82",
  "rose-pine-dawn", "tokyonight-night",
}

local groups = {
  "Normal", "StatusLine", "StatusLineNC", "Visual", "Search", "IncSearch",
  "WinSeparator", "NonText", "Pmenu",
  "@attribute", "@comment", "@comment.documentation", "@constant", "@constant.builtin",
  "@constructor", "@string.escape", "@function", "@function.builtin", "@function.macro",
  "@function.method", "@keyword", "@label", "@number", "@operator", "@property",
  "@punctuation.delimiter", "@punctuation.bracket", "@punctuation.special", "@string",
  "@string.special", "@tag", "@markup.italic", "@markup.raw", "@markup.link.label",
  "@markup.strong", "@markup.heading", "@markup.link.url", "@markup.link", "@type",
  "@type.builtin", "@variable", "@variable.builtin", "@variable.parameter",
}

local function attrs(hl)
  local bits = 0
  if hl.bold then bits = bits + 1 end
  if hl.italic then bits = bits + 2 end
  if hl.underline or hl.undercurl then bits = bits + 4 end
  if hl.reverse then bits = bits + 8 end
  if hl.strikethrough then bits = bits + 16 end
  return bits
end

local function color(value)
  return value and string.format("0x%06X", value) or "NONE"
end

local function dump_groups(lines)
  for _, group in ipairs(groups) do
    local hl = vim.api.nvim_get_hl(0, { name = group, link = false })
    lines[#lines + 1] = string.format(
      '            ("%s", face(%s, %s, %d)),', group, color(hl.fg), color(hl.bg), attrs(hl))
  end
end

local function apply(name)
  vim.cmd("highlight clear")
  vim.o.background = "dark"
  vim.cmd.colorscheme(name)
end

local out = {
  "// @generated by scripts/generate-nvim-schemes.lua. Do not edit.",
  "",
  "#[cfg(test)]",
  "use super::omarchy::Face;",
  "use super::omarchy::{face, NvimScheme, NONE};",
  "",
  "#[rustfmt::skip]",
  "pub(super) const SCHEMES: &[NvimScheme] = &[",
}

for _, name in ipairs(schemes) do
  local ok, err = pcall(apply, name)
  if not ok or vim.g.colors_name == nil then
    error("failed to load colorscheme " .. name .. ": " .. tostring(err))
  end
  out[#out + 1] = "    NvimScheme {"
  out[#out + 1] = string.format('        name: "%s",', name)
  out[#out + 1] = "        groups: &["
  dump_groups(out)
  out[#out + 1] = "        ],"
  out[#out + 1] = "    },"
end
out[#out + 1] = "];"
out[#out + 1] = ""

-- Aether fixture: ristretto's colors.toml run through the real plugin.
local colors = {}
for line in io.lines("/usr/share/omarchy/themes/ristretto/colors.toml") do
  local key, value = line:match('^(%S+)%s*=%s*"(.*)"')
  if key then colors[key] = value end
end
local palette = {
  bg = colors.background, dark_bg = colors.dark_background, darker_bg = colors.darker_background,
  lighter_bg = colors.lighter_background, fg = colors.foreground, dark_fg = colors.dark_foreground,
  light_fg = colors.light_foreground, bright_fg = colors.bright_foreground, muted = colors.muted,
  red = colors.red, yellow = colors.yellow, orange = colors.orange, green = colors.green,
  cyan = colors.cyan, blue = colors.blue, magenta = colors.magenta, brown = colors.brown,
  bright_red = colors.bright_red, bright_yellow = colors.bright_yellow,
  bright_green = colors.bright_green, bright_cyan = colors.bright_cyan,
  bright_blue = colors.bright_blue, bright_magenta = colors.bright_magenta,
  accent = colors.accent, cursor = colors.bright_foreground, foreground = colors.foreground,
  background = colors.background, selection = colors.selection,
}
vim.cmd("highlight clear")
vim.o.background = "dark"
require("lazy").load({ plugins = { "aether" } })
require("aether").setup({ colors = palette })
vim.cmd.colorscheme("aether")

local colors_file = assert(io.open("/usr/share/omarchy/themes/ristretto/colors.toml"))
out[#out + 1] = "#[cfg(test)]"
out[#out + 1] = 'pub(super) const AETHER_RISTRETTO_COLORS: &str = r##"' .. colors_file:read("*a") .. '"##;'
colors_file:close()
out[#out + 1] = ""
out[#out + 1] = "#[cfg(test)]"
out[#out + 1] = "#[rustfmt::skip]"
out[#out + 1] = "pub(super) const AETHER_RISTRETTO_FIXTURE: &[(&str, Face)] = &["
local fixture = {}
dump_groups(fixture)
for _, line in ipairs(fixture) do
  out[#out + 1] = line:sub(9)
end
out[#out + 1] = "];"
out[#out + 1] = ""

local file = assert(io.open(os.getenv("MINIMACS_OUT"), "w"))
file:write(table.concat(out, "\n"))
file:close()
